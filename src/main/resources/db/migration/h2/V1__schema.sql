-- 智慧校园服务平台 · H2（dev / test）建表脚本
-- 与 mysql/V1__schema.sql 字段一一对应，只是方言不同（IDENTITY vs AUTO_INCREMENT）

CREATE TABLE sys_user (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL,
    password    VARCHAR(100) NOT NULL,
    real_name   VARCHAR(100) NOT NULL,
    phone       VARCHAR(50),
    email       VARCHAR(100),
    gender      VARCHAR(20),
    avatar      VARCHAR(500),
    role        VARCHAR(20)  NOT NULL,
    enabled     BOOLEAN      NOT NULL DEFAULT TRUE,
    create_time TIMESTAMP    NOT NULL,
    update_time TIMESTAMP,
    CONSTRAINT uk_user_username UNIQUE (username)
);

CREATE TABLE student (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    student_no      VARCHAR(20)  NOT NULL,
    department      VARCHAR(100),
    major           VARCHAR(100),
    class_name      VARCHAR(50),
    enrollment_year VARCHAR(20),
    status          VARCHAR(20)  NOT NULL,
    dormitory       VARCHAR(100),
    total_credits   DOUBLE       DEFAULT 0,
    card_balance    DOUBLE       DEFAULT 0,
    create_time     TIMESTAMP    NOT NULL,
    update_time     TIMESTAMP,
    CONSTRAINT uk_student_user UNIQUE (user_id),
    CONSTRAINT uk_student_no   UNIQUE (student_no),
    CONSTRAINT fk_student_user FOREIGN KEY (user_id) REFERENCES sys_user (id)
);

CREATE TABLE teacher (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    teacher_no       VARCHAR(20)  NOT NULL,
    department       VARCHAR(100),
    title            VARCHAR(100),
    research_area    VARCHAR(100),
    teacher_type     VARCHAR(50),
    office           VARCHAR(100),
    political_status VARCHAR(50),
    create_time      TIMESTAMP    NOT NULL,
    update_time      TIMESTAMP,
    CONSTRAINT uk_teacher_user UNIQUE (user_id),
    CONSTRAINT uk_teacher_no   UNIQUE (teacher_no),
    CONSTRAINT fk_teacher_user FOREIGN KEY (user_id) REFERENCES sys_user (id)
);

CREATE TABLE course (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100) NOT NULL,
    code             VARCHAR(20),
    credits          DOUBLE,
    hours            INT,
    type             VARCHAR(50),
    description      VARCHAR(200),
    teacher_id       BIGINT,
    semester         VARCHAR(50),
    schedule         VARCHAR(100),
    classroom        VARCHAR(100),
    max_students     INT,
    current_students INT          NOT NULL DEFAULT 0,
    create_time      TIMESTAMP    NOT NULL,
    CONSTRAINT uk_course_code UNIQUE (code),
    CONSTRAINT fk_course_teacher FOREIGN KEY (teacher_id) REFERENCES teacher (id)
);

CREATE TABLE course_selection (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT      NOT NULL,
    course_id   BIGINT      NOT NULL,
    status      VARCHAR(20) NOT NULL,
    create_time TIMESTAMP   NOT NULL,
    CONSTRAINT uk_selection UNIQUE (student_id, course_id),
    CONSTRAINT fk_selection_student FOREIGN KEY (student_id) REFERENCES student (id),
    CONSTRAINT fk_selection_course  FOREIGN KEY (course_id)  REFERENCES course (id)
);

CREATE TABLE grade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT      NOT NULL,
    course_id   BIGINT      NOT NULL,
    score       DOUBLE      NOT NULL,
    grade_level VARCHAR(20) NOT NULL,
    credits     DOUBLE,
    status      VARCHAR(20) NOT NULL,
    semester    VARCHAR(50),
    create_time TIMESTAMP   NOT NULL,
    CONSTRAINT uk_grade UNIQUE (student_id, course_id, semester),
    CONSTRAINT fk_grade_student FOREIGN KEY (student_id) REFERENCES student (id),
    CONSTRAINT fk_grade_course  FOREIGN KEY (course_id)  REFERENCES course (id)
);

CREATE TABLE announcement (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(200) NOT NULL,
    content      TEXT,
    type         VARCHAR(50),
    publisher_id BIGINT,
    top          BOOLEAN      NOT NULL DEFAULT FALSE,
    publish_time TIMESTAMP    NOT NULL,
    create_time  TIMESTAMP    NOT NULL,
    CONSTRAINT fk_announcement_publisher FOREIGN KEY (publisher_id) REFERENCES sys_user (id)
);

CREATE TABLE news (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(200) NOT NULL,
    content      TEXT,
    cover_image  VARCHAR(500),
    category     VARCHAR(50),
    author_id    BIGINT,
    view_count   INT       NOT NULL DEFAULT 0,
    publish_time TIMESTAMP NOT NULL,
    create_time  TIMESTAMP NOT NULL,
    CONSTRAINT fk_news_author FOREIGN KEY (author_id) REFERENCES sys_user (id)
);

-- 名册按学号 / 工号查，选课记录按学生查，公告新闻按时间排序
CREATE INDEX idx_student_no       ON student (student_no);
CREATE INDEX idx_teacher_no       ON teacher (teacher_no);
CREATE INDEX idx_selection_student ON course_selection (student_id, status);
CREATE INDEX idx_selection_course  ON course_selection (course_id, status);
CREATE INDEX idx_announcement_time ON announcement (top, publish_time);
CREATE INDEX idx_news_time         ON news (publish_time);
